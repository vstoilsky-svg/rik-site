from __future__ import annotations

import re


LOCAL_KNOWLEDGE_MODEL = "local:knowledge"


def local_knowledge_answer(message: str) -> str:
    """Return a safe, useful answer when the external chat provider is unavailable."""
    normalized = re.sub(r"\s+", " ", message.strip().lower().replace("ё", "е"))

    if _matches(normalized, "контакт", "телефон", "почт", "email", "e-mail", "связаться", "адрес"):
        return (
            "Связаться с РИК можно по телефону +7 (495) 104-37-79 или по e-mail "
            "zakaz@rik-vent.ru. Адрес и схема проезда есть на странице "
            "[Контакты](/contacts)."
        )

    if _matches(normalized, "сертификат", "деклараци", "документ", "техническ", "техлист", "паспорт"):
        return (
            "Сертификаты и техническая документация собраны в разделе "
            "[Сертификаты](/certificates). Технические листы конкретных моделей также доступны "
            "на страницах оборудования в [каталоге](/products)."
        )

    if _matches(normalized, "rik-m", "rik-s", "центральн", "кондиционер", "приточн", "установк"):
        return (
            "РИК выпускает центральные вентиляционные установки RIK-M и RIK-S — модульные "
            "приточные и приточно-вытяжные решения с секциями обработки воздуха. "
            "[Открыть раздел центральных установок](/product/centralnye-ustanovki). Для подбора "
            "можно [скачать опросный лист](/downloads/oprosny-list-centralny-konditsioner.xlsx)."
        )

    if _matches(normalized, "вентилятор", "krv", "krv-v", "krv-du", "rop", "rop-k", "rr", "wrn", "vr"):
        return (
            "В линейке РИК есть крышные KRV и KRV-V, радиальные RR, осевые ROP и ROP-K, "
            "вентиляторы дымоудаления KRV-DU, а также круглые и прямоугольные канальные модели. "
            "Смотрите раздел [Вентиляторы](/products#fans). Для подбора доступен "
            "[опросный лист на вентилятор](/downloads/oprosny-list-ventilyator.xlsx)."
        )

    if _matches(normalized, "клапан", "кид", "кидм", "кгв", "рик-1", "рик-2", "рик-3", "огнезадерж", "противопожар"):
        return (
            "РИК производит противопожарные клапаны РИК-1, РИК-2 и РИК-3, клапаны "
            "избыточного давления КИД/КИДм, герметические клапаны КГВ, а также обратные "
            "клапаны и регулирующие заслонки. Модели и документы доступны в "
            "[каталоге продукции](/products)."
        )

    if _matches(normalized, "канальн", "нагревател", "охладител", "фильтр", "шумоглуш", "рекуператор", "заслонк"):
        return (
            "Канальное оборудование РИК включает вентиляторы, водяные и электрические "
            "нагреватели, охладители, фильтры, шумоглушители, рекуператоры, обратные клапаны "
            "и заслонки круглого и прямоугольного сечения. "
            "[Открыть каталог](/products)."
        )

    if _matches(normalized, "привет", "здравств", "добрый день", "добрый вечер", "доброе утро"):
        return (
            "Здравствуйте! Я помогу с продукцией РИК, документацией и подготовкой данных для "
            "расчёта. Напишите тип оборудования или маркировку, которая вас интересует."
        )

    if _matches(normalized, "спасибо", "благодар"):
        return "Пожалуйста! Если понадобится подобрать оборудование или найти документ, напишите маркировку или параметры задачи."

    if _matches(normalized, "что производ", "продукц", "оборудован", "каталог", "что есть", "ассортимент"):
        return (
            "РИК производит вентиляционное оборудование: центральные установки RIK-M/RIK-S, "
            "вентиляторы, круглое и прямоугольное канальное оборудование, противопожарные и "
            "специальные клапаны, воздуховоды, автоматику, воздушные завесы и оборудование "
            "холодоснабжения. Все группы собраны в [каталоге продукции](/products)."
        )

    return (
        "Уточните, пожалуйста, тип оборудования или маркировку — например RIK-M, KRV, RR, "
        "КИДм или канальное оборудование. Я подскажу назначение и найду нужную страницу или "
        "документ. Все группы доступны в [каталоге продукции](/products)."
    )


def _matches(value: str, *needles: str) -> bool:
    return any(needle in value for needle in needles)
