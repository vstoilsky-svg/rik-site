export interface Product {
  slug: string; name: string; marking: string; waer?: string; group: string;
  blurb: string; advantages: string[];
  sizeCols?: string[]; sizes?: SizeRow[];
  tables?: { title: string; cols: string[]; rows: SizeRow[]; note?: string; img?: string }[];
  scheme?: string; // габаритный чертёж (буквенные размеры) к таблице
  techSheet?: string; // готовый PDF-техлист для скачивания
  hideInMenu?: boolean;    // не показывать пункт в мега/мобильном меню (страница доступна по URL)
  hideInCatalog?: boolean; // не показывать карточку на хабе /products
  catalogLayout?: "standard" | "wide";
  catalogName?: string; // отдельное название только для карточки каталога
  ductFamily?: import("./duct-families").DuctFamily; // семейство воздуховодов/деталей
  contentHtml?: string;  // локализованный контент SVOK (чертежи+таблицы)
  sourceUrl?: string;    // страница-источник
  designation?: { code: string; text: string }[]; // структура обозначения (спец-вентиляторы)
  aeroCharts?: { src: string; label: string }[]; // аэродинамические графики (спец-вентиляторы)
  certificatePlaceholder?: boolean; // сертификат в оформлении // wide = карточка на всю ширину сетки
  catalogMedia?: { src: string; label: string }[]; // мультифото карточки (fallback — photo)
  pageMedia?: { src: string; label: string }[];    // мультифото hero страницы товара
  construction?: string[]; executions?: string[];
  related?: { label: string; to: string }[];
  photo?: string; placeholder?: boolean;
}
